import json
import os

OUTPUT_DIR = "data_v1-14b"
os.makedirs(OUTPUT_DIR, exist_ok=True)

# 14Bの認識境界を固定するためのシステムプロンプト
SYSTEM_PROMPT = (
    "あなたは最高精度の個人情報抽出（NER）専門AIエンジンです。\n"
    "入力されたテキストに含まれる「すべての個人情報および識別可能な組織・ロケーション情報」を漏れなく検出し、"
    "プレースホルダー名をキーとした単一のJSON辞書形式でのみ出力してください。\n"
    "文中に登場する社内同僚（〜さん）、相手先担当者（〜様）、苗字のみの表記、部署名、住所、連絡先をすべて網羅してください。\n"
    "本文の再生成(masked_text)や解説、前置き、Markdown装飾などは一切禁止です。"
)

# 【14B用データセット】短文の基本形 ＋ 複数属性が密集するビジネス実務文
