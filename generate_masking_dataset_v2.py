# 各サンプルを複数回繰り返してデータ量を確保 (エポック数補正)
formatted_data = []
for sample in masking_samples:
    messages = [
        {"role": "system", "content": SYSTEM_PROMPT},
        {"role": "user", "content": sample["input"]},
        {"role": "assistant", "content": json.dumps(sample["output"], ensure_ascii=False, indent=2)}
    ]
    # バリエーションを強固にするため複数回含める
    for _ in range(5):
        formatted_data.append({"messages": messages})

for filename in ["train.jsonl", "valid.jsonl"]:
    filepath = os.path.join(OUTPUT_DIR, filename)
    with open(filepath, "w", encoding="utf-8") as f:
        for entry in formatted_data:
            f.write(json.dumps(entry, ensure_ascii=False) + "\n")

print(f"✅ v2用の学習データセット(data_v2)を作成しました (計 {len(formatted_data)} 件)")